// ctype.h from C
#include <cctype>

// MOST ARE STATIC METHODS

// isalnum(c) ==> Checks if c is an alphanumeric character (letter or digit). 
    // Returns non-zero if true, 0 if false.

// isalpha(c) ==> Checks if c is an alphabetic character (letter). 
    // Returns non-zero if true, 0 if false.

// isblank(c) ==> Checks if c is a blank character (space or horizontal tab). 
    // Returns non-zero if true, 0 if false.

// iscntrl(c) ==> Checks if c is a control character. 
    // Returns non-zero if true, 0 if false.

// isdigit(c) ==> Checks if c is a decimal digit (0-9). 
    // Returns non-zero if true, 0 if false.

// isgraph(c) ==> Checks if c is a graphical character (any printable character except space).
    // Returns non-zero if true, 0 if false.

// islower(c) ==> Checks if c is a lowercase letter. 
    // Returns non-zero if true, 0 if false.

// isprint(c) ==> Checks if c is a printable character (including space). 
    // Returns non-zero if true, 0 if false.

// ispunct(c) ==> Checks if c is a punctuation character. 
    // Returns non-zero if true, 0 if false.

// isspace(c) ==> Checks if c is a whitespace character (space, tab, newline, carriage return, form feed, vertical tab). 
    // Returns non-zero if true, 0 if false.

// isupper(c) ==> Checks if c is an uppercase letter. 
    // Returns non-zero if true, 0 if false.

// isxdigit(c) ==> Checks if c is a hexadecimal digit (0-9, a-f, A-F). 
    // Returns non-zero if true, 0 if false.

// tolower(c) ==> Converts c to its lowercase equivalent if it is an uppercase letter. Otherwise, returns c unchanged.

// toupper(c) ==> Converts c to its uppercase equivalent if it is a lowercase letter. Otherwise, returns c unchanged.
